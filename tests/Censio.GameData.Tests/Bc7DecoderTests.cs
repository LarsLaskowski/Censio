    /// <summary>
    /// A mode 6 block with two equal endpoints and all indices 0 decodes to one colour worked out by hand: each
    /// 7-bit endpoint value 100, 50, 16 and 125 is shifted left by one and takes the P-bit 1, which gives 201, 101, 33
    /// and 251 (8 bits of precision, so the replication of the most significant bit adds nothing), and the
    /// interpolation between equal endpoints returns the endpoint.
    /// </summary>
    [TestMethod]
    [TestCategory("AC1")]
    public void Bc7DecoderDecodeBlockMode6SolidWorkedByHand()
    {
        // Arrange
        var block = Convert.FromHexString("403259268340FAFD0100000000000000");
        var rgba = new byte[PixelBytes];

        Array.Fill(rgba, (byte)0xFF);

        // Act
        Bc7Decoder.DecodeBlock(block, rgba);

        // Assert
        var expected = string.Concat(Enumerable.Repeat("C96521FB", 16));

        Assert.AreEqual(expected, Convert.ToHexString(rgba), "All 16 pixels should be the hand-worked colour");
    }

    /// <summary>
    /// A block whose first byte is 0 is the reserved mode 8 and decodes to 16 transparent black pixels, whatever the
    /// other bytes hold (BC7 format description, Mode Reference, Remarks: a block initialized to all zeroes is
    /// returned; BCnEncoder.NET 2.3.0 returns opaque magenta instead).
    /// </summary>
    /// <param name="blockHex">The block as hexadecimal text</param>
    [TestMethod]
    [TestCategory("AC1")]
    [DataRow("00000000000000000000000000000000")]
    [DataRow("00FFFFFFFFFFFFFFFFFFFFFFFFFFFFFF")]
    [DataRow("0001020304050607AABBCCDDEEFF1122")]
    public void Bc7DecoderDecodeBlockReservedModeGivesTransparentBlack(string blockHex)
    {
        // Arrange
        var block = Convert.FromHexString(blockHex);
        var rgba = new byte[PixelBytes];

        Array.Fill(rgba, (byte)0xFF);

        // Act
        Bc7Decoder.DecodeBlock(block, rgba);

        // Assert
        Assert.AreEqual(new string('0', PixelBytes * 2), Convert.ToHexString(rgba), "All pixels should be transparent black");
    }

